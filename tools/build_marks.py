"""Regenerate src/localflow/marks.py from tools/marks.px.js (the marks drawn in pxl).

    python tools/build_marks.py [path to claude-pxl]

Needs Node 22+ and claude-pxl (default C:\\Code\\_vendor\\claude-pxl).
"""
import re
import subprocess
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
pxl = Path(sys.argv[1] if len(sys.argv) > 1 else r"C:\Code\_vendor\claude-pxl") / "bin" / "pxl.js"
src = root / "tools" / "marks.px.js"
names = re.findall(r'^(?:mark|anim)\("(\w+)", (?:(\d+),|\{[^}]*fps: (\d+))', src.read_text(encoding="utf-8"), re.M)
out = ['"""The animated recording marks, drawn in pxl (tools/marks.px.js). Generated by',
       'tools/build_marks.py: edit the .px.js and run it again, not this file.',
       '',
       'Each mark is a list of frames; a frame is 9 rows of 11 characters (X the recording',
       'colour, h its light, o its dark, the rest fixed glints). FPS is frames per second."""',
       '', 'FRAMES: dict[str, list[list[str]]] = {}', 'FPS: dict[str, int] = {}', '']
for name, fps1, fps2 in names:
    text = subprocess.run(["node", str(pxl), "ascii", str(src), name, "--out", str(root / "data" / "_pxl")],
                          capture_output=True, text=True, check=True, encoding="utf-8").stdout
    frames = []
    for block in text.split("frame ")[1:]:
        rows = [m.group(1) for m in re.finditer(r"^\s+\d+ (\S{11})$", block, re.M)]
        assert len(rows) == 9, (name, rows)
        frames.append(rows)
    out.append(f"FPS[{name!r}] = {int(fps1 or fps2)}")
    out.append(f"FRAMES[{name!r}] = [")
    for rows in frames:
        out.append("    [" + ", ".join(repr(r) for r in rows[:5]) + ",")
        out.append("     " + ", ".join(repr(r) for r in rows[5:]) + "],")
    out.append("]")
    print(name, len(frames), "frames")
(root / "src" / "localflow" / "marks.py").write_text("\n".join(out) + "\n", encoding="utf-8")
